// Extracts the Material Symbols Rounded icons the app uses into src/icons/glyphs.ts.
// Run: node scripts/build-icons.mjs  (after adding a name to ICONS)
import { readFileSync, writeFileSync } from 'node:fs';

const ICONS = [
  'arrow_back', 'arrow_forward', 'arrow_upward', 'arrow_drop_down', 'chevron_left', 'chevron_right',
  'more_horiz', 'more_vert', 'tune', 'close', 'add', 'remove', 'check', 'check_circle', 'sync',
  'lock', 'lock_open', 'content_paste', 'calendar_month', 'eco', 'wb_twilight', 'restaurant', 'spa',
  'verified', 'verified_user', 'favorite', 'schedule', 'photo_library', 'forum', 'person', 'local_florist',
  'format_quote', 'flag', 'block', 'notifications', 'download', 'download_done', 'delete', 'badge',
  'travel_explore', 'credit_card', 'how_to_vote', 'upload_file', 'task', 'shield_lock', 'hourglass_top',
  'add_a_photo', 'send', 'family_restroom', 'palette', 'logout', 'error',
];
const pathOf = (file) => {
  const svg = readFileSync(file, 'utf8');
  return [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(' ');
};
const root = 'node_modules/@material-symbols';
const out = {};
for (const n of ICONS) {
  out[n] = pathOf(`${root}/svg-400/rounded/${n}.svg`);
  out[`${n}-fill`] = pathOf(`${root}/svg-400/rounded/${n}-fill.svg`);
}
// The welcome mark (6a) is the thin-weight folded hands.
out['folded_hands-thin'] = pathOf(`${root}/svg-200/rounded/folded_hands.svg`);

writeFileSync(
  'src/icons/glyphs.ts',
  '// GENERATED by scripts/build-icons.mjs from Material Symbols Rounded (Apache-2.0). Do not edit.\n' +
    '// Paths use the 0 -960 960 960 viewBox.\n' +
    `export const GLYPHS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "')} as const;\n`,
);
console.log(Object.keys(out).length, 'glyphs');
